const { chromium } = require('playwright');
const TOKEN = process.argv[2];
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  await page.addInitScript((t) => { if (!sessionStorage.getItem('i')) { localStorage.setItem('svc_token_externo', t); sessionStorage.setItem('i', '1'); } }, TOKEN);
  await page.route('**/api/ia-service-publico/login/iniciar', (r) => r.fulfill({ json: { challengeId: 'c1', destino: '+55 65 *****-9999' } }));
  await page.route('**/api/ia-service-publico/login/verificar', (r) => r.fulfill({ json: { token: TOKEN } }));
  await page.goto('http://127.0.0.1:4993/iaservice/j2a', { waitUntil: 'networkidle' });
  await page.waitForSelector('.account-summary');
  await page.click('.account-summary'); await page.click('#logout-btn');
  await page.waitForSelector('#access-screen:not([hidden])');
  await page.fill('#phone-input', '65999990000');
  await page.click('#request-code-btn');
  await page.waitForSelector('#code-form:not([hidden])');
  const inputs = page.locator('#code-row input');
  for (let i = 0; i < 6; i += 1) await inputs.nth(i).fill(String(i + 1));
  await page.click('#verify-code-btn');
  await page.waitForSelector('#radar-screen:not([hidden])');
  await page.click('.account-summary'); await page.click('#logout-btn');
  await page.waitForSelector('#access-screen:not([hidden])');
  const faseTelefone = await page.locator('#phone-form').isVisible();
  const faseCodigoOculta = await page.locator('#code-form').isHidden();
  const codigos = await inputs.evaluateAll((els) => els.map((e) => e.value).join(''));
  const ok = faseTelefone && faseCodigoOculta && codigos === '';
  console.log(`${ok ? 'OK' : 'FALHA'}: apos Sair -> passo telefone visivel=${faseTelefone}, codigo oculto=${faseCodigoOculta}, digitos antigos="${codigos}"`);
  await browser.close();
  process.exitCode = ok ? 0 : 1;
})().catch((e) => { console.error(e); process.exitCode = 1; });
