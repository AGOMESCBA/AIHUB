const { chromium } = require('playwright');
const TOKEN = process.argv[2];
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1400, height: 800 } });
  await page.addInitScript((t) => { localStorage.setItem('svc_token_externo', t); if (!sessionStorage.getItem('iniciado')) { localStorage.removeItem('iaservice_j2a_theme'); sessionStorage.setItem('iniciado', '1'); } }, TOKEN);
  await page.goto('http://127.0.0.1:4993/iaservice/j2a', { waitUntil: 'networkidle' });
  await page.waitForSelector('#theme-toggle');
  const r = [];
  const chk = (n, ok) => { r.push(ok); console.log(`${ok ? 'OK   ' : 'FALHA'} ${n}`); };
  chk('inicial: menu fechado e icone do sistema', (await page.locator('#theme-menu').isHidden()) && (await page.locator('#theme-toggle').innerText()).includes('🖥'));
  await page.click('#theme-toggle');
  chk('clicar abre o menu com 3 opcoes', (await page.locator('#theme-menu').isVisible()) && (await page.locator('#theme-menu button').count()) === 3);
  await page.screenshot({ path: 'tmp/tema-menu-aberto.png', clip: { x: 800, y: 0, width: 600, height: 200 } });
  await page.click('[data-theme-option="dark"]');
  chk('escolher Escuro: aplica, fecha o menu e botao vira lua', (await page.evaluate(() => document.documentElement.dataset.theme)) === 'dark' && (await page.locator('#theme-menu').isHidden()) && (await page.locator('#theme-toggle').innerText()).includes('🌙'));
  await page.click('#theme-toggle');
  await page.click('[data-theme-option="light"]');
  chk('escolher Claro: botao vira sol', (await page.locator('#theme-toggle').innerText()).includes('☀'));
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForSelector('#theme-toggle');
  chk('apos F5 mantem Claro e o icone', (await page.evaluate(() => document.documentElement.dataset.theme)) === 'light' && (await page.locator('#theme-toggle').innerText()).includes('☀'));
  await page.click('#theme-toggle');
  await page.keyboard.press('Escape');
  chk('Esc fecha o menu', await page.locator('#theme-menu').isHidden());
  await page.click('#theme-toggle');
  await page.mouse.click(300, 400);
  chk('clicar fora fecha o menu', await page.locator('#theme-menu').isHidden());
  await browser.close();
  process.exitCode = r.every(Boolean) ? 0 : 1;
})().catch((e) => { console.error(e); process.exitCode = 1; });
